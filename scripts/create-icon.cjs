const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const size = 64;
const table = Array.from({ length: 256 }, (_, n) => {
  for (let k = 0; k < 8; k++) n = n & 1 ? 0xedb88320 ^ (n >>> 1) : n >>> 1;
  return n >>> 0;
});
function crc(bytes) { let n = 0xffffffff; for (const byte of bytes) n = table[(n ^ byte) & 255] ^ (n >>> 8); return (n ^ 0xffffffff) >>> 0; }
function chunk(type, data) { const name = Buffer.from(type); const length = Buffer.alloc(4); length.writeUInt32BE(data.length); const checksum = Buffer.alloc(4); checksum.writeUInt32BE(crc(Buffer.concat([name, data]))); return Buffer.concat([length, name, data, checksum]); }
const pixels = Buffer.alloc((size * 4 + 1) * size);
for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
  const offset = y * (size * 4 + 1) + 1 + x * 4;
  const inside = Math.hypot(x - 31.5, y - 31.5) <= 29;
  const eye = (Math.abs(x - 23) <= 3 || Math.abs(x - 40) <= 3) && y >= 25 && y <= 36;
  pixels.set(inside ? (eye ? [247, 242, 225, 255] : [72, 100, 78, 255]) : [0, 0, 0, 0], offset);
}
const header = Buffer.alloc(13); header.writeUInt32BE(size, 0); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
const provenance = Buffer.from('impeccable:prompt\0Origin: locally authored geometric application icon, generated by scripts/create-icon.cjs. Teal circular body with two cream eyes. No AI-generated or third-party image.');
const png = Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), chunk('IHDR', header), chunk('tEXt', provenance), chunk('IDAT', zlib.deflateSync(pixels)), chunk('IEND', Buffer.alloc(0))]);
const target = path.resolve(__dirname, '../src/assets'); fs.mkdirSync(target, { recursive: true }); fs.writeFileSync(path.join(target, 'icon.png'), png);
const icoHeader = Buffer.alloc(22); icoHeader.writeUInt16LE(1, 2); icoHeader.writeUInt16LE(1, 4); icoHeader[6] = size; icoHeader[7] = size; icoHeader.writeUInt16LE(1, 10); icoHeader.writeUInt16LE(32, 12); icoHeader.writeUInt32LE(png.length, 14); icoHeader.writeUInt32LE(22, 18); fs.writeFileSync(path.join(target, 'icon.ico'), Buffer.concat([icoHeader, png]));
console.log('Created local geometric app icon.');
